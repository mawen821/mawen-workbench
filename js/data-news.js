// 获取指定日期的新闻，如果没有则返回空数组
function getNewsByDate(dateStr) {
  return NEWS_DATA[dateStr] || [];
}

// 获取最近几天的所有新闻
function getRecentNews(days = 3) {
  const result = [];
  const today = new Date();
  for (let i = 0; i < days; i++) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    const news = getNewsByDate(dateStr);
    news.forEach(n => {
      n.date = dateStr;
      result.push(n);
    });
  }
  // 兜底：若最近 days 天均无数据（例如自动化漏更），回退到最新一个有数据的一天，避免板块空白
  if (result.length === 0) {
    const allDates = Object.keys(NEWS_DATA).sort().reverse();
    for (const ds of allDates) {
      const news = getNewsByDate(ds);
      if (news.length) {
        news.forEach(n => { n.date = ds; result.push(n); });
        break;
      }
    }
  }
  return result;
}

