/* 按天取模，返回当日的"今日牌面卡"（前端可直接使用） */
function advTodayItem() {
  if (typeof ADV_DAILY === 'undefined' || !ADV_DAILY.length) return null;
  var d = new Date();
  var start = Date.UTC(d.getUTCFullYear(), 0, 0);
  var day = Math.floor((d.getTime() - start) / 86400000);
  return ADV_DAILY[day % ADV_DAILY.length];
}
