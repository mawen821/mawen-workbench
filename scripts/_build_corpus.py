"""一次性构建语料库：scripts/corpus/<module>.json
每个模块一组 rounds，云端按 (今天-纪元).days % len(rounds) 取一轮。
日期字段用 {DATE}/{DATE8}/{ISOWEEK}/{WEEKCN}/{YEAR} 占位符，运行时填当天。
纯数据、零外部依赖。改内容只需编辑本文件重跑，或直接在 corpus/*.json 增删条目。
"""
import json
import os

OUT = os.path.join(os.path.dirname(__file__), "corpus")
os.makedirs(OUT, exist_ok=True)


def emit(module, rounds):
    path = os.path.join(OUT, f"{module}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"module": module, "items": rounds}, f, ensure_ascii=False, indent=1)
    print(f"  {module:18s} {len(rounds)} 轮")


# ---------------- 构造器 ----------------
def W(en, ph, cn, ex):
    return {"en": en, "phonetic": ph, "cn": cn, "example": ex}


def SP(scene, en, cn):
    return {"scene": scene, "en": en, "cn": cn}


def RD(title, level, diff, paras, vocab):
    return {"title": title, "level": level, "difficulty": diff,
            "paragraphs": [{"en": e, "cn": c} for e, c in paras],
            "vocabulary": [{"word": w, "meaning": m} for w, m in vocab]}


def GR(gid, title, icon, intro, sections, tip):
    return {"id": gid, "title": title, "icon": icon, "intro": intro,
            "sections": [{"heading": h, "content": c, "examples": ex} for h, c, ex in sections],
            "tip": tip}


